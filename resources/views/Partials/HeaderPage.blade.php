        function updateTotalHarga() {
            let total = 0;

            // Loop melalui setiap item dalam keranjang (dengan class "cart-list")
            document.querySelectorAll(".cart-list").forEach(item => {
                const checkbox = item.querySelector(".item-checkbox");
                const quantityInput = item.querySelector(".quantity");

                // Hanya hitung item yang dicentang
                if (checkbox && checkbox.checked) {
                    const quantity = parseInt(quantityInput.value) || 1; // Ambil jumlah, default 1 kalau kosong/invalid
                    const price = parseFloat(quantityInput.dataset.price) || 0; // Ambil harga dari data attribute
                    total += quantity * price; // Hitung subtotal dan tambahkan ke total
                }
            });

            // Update tampilan total harga ke elemen dengan id "total-price"
            const totalPriceElement = document.querySelector("#total-price");
            if (totalPriceElement) {
                totalPriceElement.textContent = "Rp. " + total.toLocaleString("id-ID"); // Format rupiah
            }
        }


        function tambahJumlah(btn) {
            const input = btn.parentElement.querySelector(".quantity");
            const max = parseInt(input.dataset.max) || 999; // Ambil batas maksimal jumlah
            let val = parseInt(input.value) || 1; // Ambil nilai sekarang, default 1

            // Tambah jumlah jika belum mencapai maksimal
            if (val < max) {
                input.value = val + 1;
                updateTotalHarga(); // Update total harga setelah jumlah berubah
            }
        }



        function kurangiJumlah(btn) {
            const input = btn.parentElement.querySelector(".quantity");
            const min = parseInt(input.getAttribute("min")) || 1; // Ambil batas minimal (biasanya 1)
            let val = parseInt(input.value) || min;

            // Kurangi jumlah jika belum mencapai batas minimal
            if (val > min) {
                input.value = val - 1;
                updateTotalHarga(); // Update total harga setelah jumlah berubah
            }
        }



        document.addEventListener("DOMContentLoaded", function () {
              // Tambahkan event listener ke semua input jumlah (class .quantity)
              document.querySelectorAll(".quantity").forEach(input => {
                  input.addEventListener("input", function () {
                      const min = parseInt(this.getAttribute("min")) || 1;
                      const max = parseInt(this.getAttribute("max")) || 999;
                      let val = parseInt(this.value) || min;

                      // Validasi supaya input jumlah tetap dalam rentang [min, max]
                      if (val < min) val = min;
                      if (val > max) val = max;

                      this.value = val;
                      updateTotalHarga(); // Update total harga jika ada perubahan jumlah
                  });
              });

              // Tambahkan event listener untuk semua checkbox item
              document.querySelectorAll(".item-checkbox").forEach(cb => {
                  cb.addEventListener("change", updateTotalHarga); // Update total harga saat centang berubah
              });

              updateTotalHarga(); // Hitung total pertama kali saat halaman dimuat
          });



        </script>


